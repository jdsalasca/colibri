//! Generate a standalone Rust program from a parsed `.colibri` component.
//!
//! The generated program wraps the SFC script in `fn main`, evaluates template
//! expressions with the Rust compiler (not an interpreter), builds the shared
//! IR at runtime and renders it with `colibri-ssr`. The output keeps the same
//! safety rules as static rendering: tags, attributes and URLs are validated
//! by the renderer, and dynamic values are escaped as text or attributes.

use colibri_parser::{AttributeValue, SourceSpan, TemplateElement, TemplateNode};
use std::error::Error;
use std::fmt;

/// A code generation failure tied to a source span.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    /// Human-readable explanation.
    pub message: String,
    /// Location in the original `.colibri` file.
    pub span: SourceSpan,
}

impl CodegenError {
    fn new(message: impl Into<String>, span: &SourceSpan) -> Self {
        Self {
            message: message.into(),
            span: span.clone(),
        }
    }
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}:{}..{}: [codegen] {}",
            self.span.file, self.span.start_byte, self.span.end_byte, self.message
        )
    }
}

impl Error for CodegenError {}

/// Generate a complete Rust source file with a `main` that prints HTML.
///
/// `component_name` is only used in the header comment. The caller is
/// responsible for compiling the output with `colibri-ir` and `colibri-ssr`
/// available as dependencies.
pub fn generate(
    component_name: &str,
    component: &colibri_parser::SingleFileComponent,
) -> Result<String, CodegenError> {
    let tree = nodes_expr(&component.template.nodes)?;
    let span = span_expr(&component.template.span);
    let mut code = String::new();
    code.push_str("// Generated by colibri-codegen. Do not edit.\n");
    code.push_str(&format!("// Component: {component_name}\n"));
    code.push_str("#![allow(unused)]\nfn main() {\n");
    push_script(
        &mut code,
        component
            .script
            .as_ref()
            .map(|block| block.content.as_str()),
    );
    code.push_str(&format!(
        "    let __colibri_generated_node = ::colibri_ir::Node::Fragment {{ children: ::std::vec![{tree}], span: {span} }};\n"
    ));
    code.push_str("    match ::colibri_ssr::render_static(&__colibri_generated_node) {\n");
    code.push_str("        Ok(html) => print!(\"{html}\"),\n");
    code.push_str(
        "        Err(error) => { eprintln!(\"{error}\"); std::process::exit(1); }\n    }\n}\n",
    );
    Ok(code)
}

fn push_script(code: &mut String, script: Option<&str>) {
    let Some(script) = script else {
        return;
    };
    if script.trim().is_empty() {
        return;
    }
    code.push_str("    // <script lang=\"rust\">\n");
    for line in script.lines() {
        code.push_str("    ");
        code.push_str(line);
        code.push('\n');
    }
    code.push_str("    // </script>\n");
}

fn nodes_expr(nodes: &[TemplateNode]) -> Result<String, CodegenError> {
    let mut parts = Vec::new();
    for node in nodes {
        if let Some(part) = node_expr(node)? {
            parts.push(part);
        }
    }
    Ok(parts.join(", "))
}

fn node_expr(node: &TemplateNode) -> Result<Option<String>, CodegenError> {
    match node {
        TemplateNode::Text(text) => Ok(Some(format!(
            "::colibri_ir::Node::Text {{ value: {}.to_owned(), span: {} }}",
            literal(&text.value),
            span_expr(&text.span)
        ))),
        TemplateNode::Interpolation(interpolation) => Ok(Some(format!(
            "::colibri_ir::Node::Text {{ value: format!(\"{{}}\", ({})), span: {} }}",
            interpolation.expression,
            span_expr(&interpolation.span)
        ))),
        TemplateNode::Comment(_) => Ok(None),
        TemplateNode::Element(element) => element_expr(element).map(Some),
    }
}

fn element_expr(element: &TemplateElement) -> Result<String, CodegenError> {
    if element.tag.bytes().any(|byte| byte.is_ascii_uppercase()) {
        return Err(CodegenError::new(
            format!(
                "component <{}> is not resolved; codegen only supports HTML tags",
                element.tag
            ),
            &element.span,
        ));
    }
    let attributes = attributes_expr(element)?;
    let children = nodes_expr(&element.children)?;
    Ok(format!(
        "::colibri_ir::Node::Element(::colibri_ir::Element {{ tag: {}.to_owned(), attributes: ::std::vec![{attributes}], children: ::std::vec![{children}], span: {} }})",
        literal(&element.tag),
        span_expr(&element.span)
    ))
}

fn attributes_expr(element: &TemplateElement) -> Result<String, CodegenError> {
    let mut attributes = Vec::new();
    for attribute in &element.attributes {
        attributes.push(attribute_expr(attribute)?);
    }
    Ok(attributes.join(", "))
}

fn attribute_expr(attribute: &colibri_parser::TemplateAttribute) -> Result<String, CodegenError> {
    if let Some(event) = attribute.name.strip_prefix("on:") {
        return Err(CodegenError::new(
            format!("event on:{event} requires the client runtime (M07)"),
            &attribute.span,
        ));
    }
    let span = span_expr(&attribute.span);
    let name = literal(&attribute.name);
    match &attribute.value {
        AttributeValue::Boolean => Ok(format!(
            "::colibri_ir::Attribute::Boolean {{ name: {name}.to_owned(), span: {span} }}"
        )),
        AttributeValue::Literal(value) => Ok(format!(
            "::colibri_ir::Attribute::Static {{ name: {name}.to_owned(), value: {}.to_owned(), span: {span} }}",
            literal(value)
        )),
        AttributeValue::Expression(expression) => Ok(format!(
            "::colibri_ir::Attribute::Static {{ name: {name}.to_owned(), value: format!(\"{{}}\", ({expression})), span: {span} }}"
        )),
    }
}

fn span_expr(span: &SourceSpan) -> String {
    format!(
        "::colibri_ir::SourceSpan {{ file: {}.to_owned(), start_byte: {}, end_byte: {} }}",
        literal(&span.file),
        span.start_byte,
        span.end_byte
    )
}

/// Rust debug formatting produces a valid string literal with escapes.
fn literal(value: &str) -> String {
    format!("{value:?}")
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

    use super::*;
    use colibri_parser::parse;

    fn code(source: &str) -> String {
        let component = parse("test.colibri", source).unwrap();
        generate("Test", &component).unwrap()
    }

    #[test]
    fn generates_static_nodes_and_render_call() {
        let output = code("<template><p>Hola</p></template>");
        assert!(output.contains("::colibri_ir::Node::Text"));
        assert!(output.contains("::colibri_ir::Node::Element"));
        assert!(output.contains("::colibri_ssr::render_static"));
        assert!(output.contains("fn main()"));
    }

    #[test]
    fn wraps_script_inside_main() {
        let output = code(
            "<script lang=\"rust\">let name = \"Ada\";</script><template><p>{name}</p></template>",
        );
        let script = output.find("let name").expect("script present");
        let node = output.find("__colibri_generated_node").expect("node");
        assert!(script < node);
        assert!(output.contains("format!(\"{}\", (name))"));
    }

    #[test]
    fn escapes_literals() {
        let output = code("<template><p title=\"a&quot;b\">x</p></template>");
        assert!(output.contains("\"a&quot;b\""));
        assert!(output.contains(".to_owned()"));
    }

    #[test]
    fn rejects_events_and_components() {
        let component = parse(
            "test.colibri",
            "<template><button on:click={go}>x</button></template>",
        )
        .unwrap();
        let error = generate("Test", &component).unwrap_err();
        assert!(error.message.contains("event"));

        let component = parse("test.colibri", "<template><Card/></template>").unwrap();
        let error = generate("Test", &component).unwrap_err();
        assert!(error.message.contains("component"));
    }
}
